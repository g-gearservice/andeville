// The English text lives in the pages and scripts; this collects it.
//   node api/i18n/sync.mjs          writes en.json (what translators work from) and pay/public/i18n.js (the pay page's strings)
//   node api/i18n/sync.mjs --check  exits 1 if either is stale, or a translation misses a key or changes the markup
// Marked in HTML as data-i18n="key" (the element's inner HTML) and data-i18n-attr="attr:key;attr:key"; in scripts as
// T("key", "English"). One key may sit in several places as long as its English is the same everywhere.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../../", import.meta.url), here = new URL("./", import.meta.url);
const read = p => readFileSync(new URL(p, root), "utf8");
const PAGES = ["index", "products", "help", "about", "teams", "contact", "policy", "account"].map(p => `site/${p}.html`).concat("pay/public/index.html");
const SCRIPTS = ["site/common.js", "site/app.js", "site/account.js", "pay/public/pay.js"];
const unesc = s => s.replace(/&(amp|lt|gt|quot|#39);/g, (_, e) => ({ amp: "&", lt: "<", gt: ">", quot: '"', "#39": "'" })[e]);

export function extract() {
  const en = {};
  const put = (k, v, where) => {
    if (!/^[a-z0-9_.]+$/.test(k)) throw new Error(`${where}: bad key "${k}"`);
    if (k in en && en[k] !== v) throw new Error(`${where}: "${k}" is already "${en[k]}", here it is "${v}"`);
    en[k] = v;
  };
  for (const file of PAGES) {
    const s = read(file);
    for (const m of s.matchAll(/<([a-z][a-z0-9]*)\b[^>]*?\sdata-i18n="([^"]+)"[^>]*>/g)) {
      // inner HTML: on to this element's own closing tag, counting any of the same name nested inside
      const tags = new RegExp(`<(/?)${m[1]}\\b[^>]*>`, "g");
      tags.lastIndex = m.index + m[0].length;
      let depth = 1, t;
      while (depth && (t = tags.exec(s))) depth += t[1] ? -1 : 1;
      if (depth) throw new Error(`${file}: "${m[2]}" is never closed`);
      put(m[2], s.slice(m.index + m[0].length, t.index).trim(), file);
    }
    for (const m of s.matchAll(/<[a-z][^>]*?\sdata-i18n-attr="([^"]+)"[^>]*>/g))
      for (const pair of m[1].split(";")) {
        const [a, k] = pair.split(":").map(x => x.trim());
        const v = new RegExp(`\\s${a}="([^"]*)"`).exec(m[0]);
        if (!v) throw new Error(`${file}: no ${a} attribute for "${k}"`);
        put(k, unesc(v[1]), file);
      }
  }
  for (const file of SCRIPTS)
    for (const m of read(file).matchAll(/\bT\(\s*"([^"]+)"\s*,\s*("(?:[^"\\]|\\.)*")/g)) put(m[1], JSON.parse(m[2]), file);
  return en;
}

const locales = () => readdirSync(here).filter(f => f.endsWith(".json") && f !== "en.json").sort();
const load = f => JSON.parse(readFileSync(new URL(f, here), "utf8"));
const out = o => JSON.stringify(o, null, 2) + "\n";
const payJs = () => "// Generated by api/i18n/sync.mjs from api/i18n/*.json (the pay.* keys). Do not edit.\nconst PAY_I18N = "
  + JSON.stringify(Object.fromEntries(locales().map(f => [f.slice(0, -5), Object.fromEntries(Object.entries(load(f)).filter(([k]) => k.startsWith("pay.")))]))) + ";\n";

// What a translation must keep exactly: the tags, the {placeholders}, and how many items a comma list has.
const shape = (k, v) => [...(v.match(/<[^>]+>/g) || []), ...(v.match(/\{\w+\}/g) || []), ...(k.endsWith(".list") ? [`${v.split(",").length} items`] : [])].sort().join(" ");

export function problems() {
  const en = extract(), bad = [];
  if (out(en) !== readFileSync(new URL("en.json", here), "utf8")) bad.push("en.json is stale: run node api/i18n/sync.mjs");
  if (payJs() !== read("pay/public/i18n.js")) bad.push("pay/public/i18n.js is stale: run node api/i18n/sync.mjs");
  for (const f of locales()) {
    const d = load(f);
    for (const k in en) {
      if (typeof d[k] !== "string" || !d[k].trim()) bad.push(`${f}: "${k}" is missing`);
      else if (shape(k, d[k]) !== shape(k, en[k])) bad.push(`${f}: "${k}" changes the markup: ${shape(k, d[k])} (English: ${shape(k, en[k])})`);
    }
    for (const k in d) if (!(k in en)) bad.push(`${f}: "${k}" is not in the pages any more`);
  }
  return bad;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const bad = problems();
    bad.forEach(b => console.error(b));
    console.log(bad.length ? `${bad.length} problem(s)` : "i18n in step");
    process.exit(bad.length ? 1 : 0);
  }
  writeFileSync(new URL("en.json", here), out(extract()));
  writeFileSync(new URL("pay/public/i18n.js", root), payJs());
  console.log(`en.json: ${Object.keys(extract()).length} keys`);
}
